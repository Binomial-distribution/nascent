// toy-sidecar 板级配置。
// 引脚可因板载占用微调，但改动必须同步到 README 的接线表。
#pragma once

#include <stdint.h>

// ---------------------------------------------------------------------------
// 引脚
// ---------------------------------------------------------------------------
#define PIN_DHT11        4   // 单总线，需 4.7k 上拉到 3V3
#define PIN_WS2812B      6   // RMT 单线
#define PIN_AO3400_GATE  7   // HIGH = 导通 = 等效按下原按键；串 1k，栅极 47k 下拉
#define PIN_FSR_L        1   // ADC1_CH0
#define PIN_FSR_R        2   // ADC1_CH1，demo 未接
#define PIN_I2C_SDA      8
#define PIN_I2C_SCL      9

// demo 只焊了一片 FSR402。置 1 时启用右侧那片。
#define TOY_HAS_FSR_R    0

// ---------------------------------------------------------------------------
// 对端 MAC：验证期用固定白名单，不做动态配对。
// 烧录前用 k10-controller 串口打印的 MAC 替换。
// ---------------------------------------------------------------------------
static const uint8_t PEER_MAC_K10[6] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00};

#define ESPNOW_CHANNEL   1

// ---------------------------------------------------------------------------
// 采样与判定
// ---------------------------------------------------------------------------
#define FSR_CONTACT_ADC        600    // 高于此值视为有接触，需按实物标定
#define FSR_RHYTHM_LO_HZ       1.0f
#define FSR_RHYTHM_HI_HZ       2.0f

#define IMU_STILL_VAR_MG2      2500   // 加速度方差低于此值视为静止
#define IMU_MOTION_VAR_MG2     8000   // 高于此值视为明显运动

#define INSERT_CONFIRM_MS      2000   // 条件持续多久才敢下 inserted 结论
#define INSERT_RELEASE_MS      1500

// ---------------------------------------------------------------------------
// 原按键时序。
//
// 2026-08-28 实测原板语义：长按约 1s = 电源开关切换（开机 / 关机），
// 瞬时短接 = 切档，关机态下短按无效。开机后停在第 1 档。
// 长按不是"关机"而是"取反"，这一点决定了 ao3400.cpp 的整个状态机。
// 这套时序只描述原板行为，与用什么器件去短接触点无关。
// ---------------------------------------------------------------------------
#define BTN_SHORT_MS           120    // 人手能复现的最短有效按压约 100ms，60ms 从未验证过
#define BTN_LONG_MS            1200   // 实测约 1s 开机，留余量
#define BTN_GAP_MS             350    // 两次短按之间的最小间隔
#define BTN_POWER_GAP_MS       600    // 两次长按之间的间隔，给原板开关机留响应时间
#define ORIGINAL_STEP_COUNT    9      // 原板九档

// ---------------------------------------------------------------------------
// 电机观测（IMU 间接反馈）
//
// 原板不给任何电气反馈，固件对"它现在是开还是关"的记录是开环的。
// MPU6050 能感知电机振动，用来修正这个记录，但**永不驱动按键**。
//
// 阈值必须在实物上标定：置 MOTOR_SENSE_ENABLED=0 烧一版，
// 跑五种场景各约 10s 记录串口打印的 jerk / var
// （关机静置、关机手持晃动、开机1档静置、开机8档静置、开机手持晃动），
// 取"关机手持晃动"的上界与"开机1档静置"的下界之间，再置 1。
// ---------------------------------------------------------------------------
#define MOTOR_SENSE_ENABLED    0      // 0 = 只打串口日志，不影响任何逻辑
#define MOTOR_JERK_ON_MG2      4000   // 占位值，待标定
#define MOTOR_JERK_OFF_MG2     2000   // 滞回下沿，占位值，待标定
#define MOTOR_CONFIRM_MS       600    // 结论需持续这么久才翻转
#define STOP_VERIFY_MS         1500   // stop 发完长按后等多久复查

// ---------------------------------------------------------------------------
// 灯
// ---------------------------------------------------------------------------
#define LED_BRIGHTNESS         120    // 0-255，情趣场景不需要刺眼
